#!/usr/bin/env node
// Generates lib/api-types.ts from docs/openapi.json (issue #155).
// Dependency-free on purpose: no package install, and the lockfile stays untouched.
// Usage: node scripts/gen-api-types.mjs            (writes lib/api-types.ts)
//        node scripts/gen-api-types.mjs --check    (exits 1 if the committed file is stale; used by CI)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const spec = JSON.parse(readFileSync(resolve(root, 'docs/openapi.json'), 'utf8'));
const out = resolve(root, 'lib/api-types.ts');

const refName = (ref) => ref.split('/').pop();

/** JSON Schema -> TypeScript type text. Unknown shapes fall back to `unknown`, never `any`. */
function toTs(schema, indent = '') {
  if (!schema) return 'unknown';
  if (schema.$ref) return refName(schema.$ref);
  if (schema.nullable) return `${toTs({ ...schema, nullable: false }, indent)} | null`;
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(' | ');
  if (schema.oneOf || schema.anyOf) return (schema.oneOf ?? schema.anyOf).map((s) => toTs(s, indent)).join(' | ');
  if (schema.allOf) return schema.allOf.map((s) => toTs(s, indent)).join(' & ');
  switch (schema.type) {
    case 'string': return 'string';
    case 'integer':
    case 'number': return 'number';
    case 'boolean': return 'boolean';
    case 'array': return `${toTs(schema.items, indent)}[]`;
    case 'object': {
      if (!schema.properties) return schema.additionalProperties ? `Record<string, ${toTs(schema.additionalProperties === true ? null : schema.additionalProperties, indent)}>` : 'Record<string, unknown>';
      const required = new Set(schema.required ?? []);
      const inner = `${indent}  `;
      const lines = Object.entries(schema.properties).map(
        ([k, v]) => `${inner}${JSON.stringify(k)}${required.has(k) ? '' : '?'}: ${toTs(v, inner)};`,
      );
      return `{\n${lines.join('\n')}\n${indent}}`;
    }
    default: return 'unknown';
  }
}

/** Response type for one operation: the 200 JSON body, or `void`. */
const successSchema = (op) => op.responses?.['200']?.content?.['application/json']?.schema;

const lines = [
  '// GENERATED by scripts/gen-api-types.mjs from docs/openapi.json. Do not edit by hand.',
  '/* eslint-disable */',
  '',
];

for (const [name, schema] of Object.entries(spec.components?.schemas ?? {})) {
  lines.push(`export type ${name} = ${toTs(schema)};`, '');
}

lines.push('export interface ApiOperations {');
for (const [path, item] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(item)) {
    if (!op.operationId) continue;
    const body = op.requestBody?.content?.['application/json']?.schema;
    lines.push(`  ${JSON.stringify(`${method.toUpperCase()} ${path}`)}: {`);
    lines.push(`    operationId: ${JSON.stringify(op.operationId)};`);
    lines.push(`    body: ${body ? toTs(body, '    ') : 'never'};`);
    lines.push(`    response: ${successSchema(op) ? toTs(successSchema(op), '    ') : 'void'};`);
    lines.push('  };');
  }
}
lines.push('}', '');

const text = lines.join('\n');
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(out, 'utf8'); } catch { /* missing file counts as stale */ }
  if (current !== text) {
    console.error('lib/api-types.ts is stale. Run: node scripts/gen-api-types.mjs');
    process.exit(1);
  }
  console.log('lib/api-types.ts is up to date');
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out}`);
}
